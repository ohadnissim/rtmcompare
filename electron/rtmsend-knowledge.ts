// ── Archetype taxonomy ────────────────────────────────────────────────

/**
 * Tags that describe a plugin's character. A plugin can carry multiple
 * tags (Pro-Q 4 is parametric AND mastering-grade AND linear-phase AND
 * mid-side AND dynamic). Recommendations match against the SET of
 * tags, not a single category.
 */
export type ArchetypeTag =
  // Architecture
  | 'parametric'         // N adjustable bands, freq/gain/Q on each
  | 'graphic'            // Fixed-frequency slider EQ (ISO bands)
  | 'console-strip'      // Channel-strip emulation (Neve 1073, SSL E/G/X)
  | 'pultec'             // Boost+atten interaction, fixed/switched freqs
  | 'tilt'               // Single rotation point tonal balance
  | 'air-band'           // Specialty HF band (Maag, Slate Air, NLS Air)
  | 'spline'             // Curve-drawing EQ (Voxengo CurveEQ)

  // Behavior
  | 'dynamic'            // Frequency-dependent compression (TDR Nova, F6)
  | 'mid-side'           // Explicit M/S routing
  | 'linear-phase'       // No phase shift mode
  | 'minimum-phase'      // Standard IIR

  // Coloration / use case
  | 'vintage'            // Analog modeling, harmonic coloration
  | 'transparent'        // Surgical, no character
  | 'mastering-grade'    // Designed for mastering specifically
  | 'mixing'             // Better suited for tracking/mixing than mastering

  // Filter-only specialties
  | 'high-pass'          // Specialty HPF
  | 'low-pass'           // Specialty LPF

  // Source-separation aware
  | 'stem-aware'         // Independent EQ per stem (Vocals/Bass/Drums/Other)

  // Spectral-matching tools — store a reference snapshot internally
  // and apply a continuous learned curve. The curve isn't addressable
  // via discrete band params; user controls only Amount + Smoothing.
  | 'match-eq'           // Ozone Match EQ, Voxengo CurveEQ match mode

/**
 * Why a plugin is a good fit for a given move. Used for showing the
 * user a reason in the "Best plugin for this move" UI.
 */
export interface RecommendationReason {
  plugin_name: string
  score: number        // 0..1 — higher = better fit
  reasoning: string    // human-readable
}

// ── Reference profile schema ──────────────────────────────────────────

/**
 * Full reference data for a single plugin. Generated by probing the
 * loaded plugin once per session. Persists to disk so subsequent
 * launches don't re-probe.
 */
export interface ReferenceProfile {
  /** VST3 createIdentifierString() — stable across paths/versions. */
  plugin_id: string
  /** Display name as the plugin reports it. */
  name: string
  /** Manufacturer / vendor if discoverable. */
  vendor?: string
  /** Total parameter count seen at probe time. */
  parameter_count: number
  /** ISO timestamp of the probe. */
  scanned_at: string
  /** RTMsend version that did the probe — for reproducibility. */
  rtmsend_version: string
  /** Tags describing the plugin's character. */
  archetype_tags: ArchetypeTag[]
  /** The active Profile if one exists (hand-coded or auto-detected),
   *  or null if the plugin doesn't fit RTM's 9-band Send model. */
  active_profile: Profile | null
  /** Full parameter dump at probe time (default values, not user state). */
  raw_parameters: ParameterSnapshot[]
  /** Free-form notes — anything we want to remember about the plugin. */
  notes?: string
}

// ── Storage layer ─────────────────────────────────────────────────────

/**
 * Knowledge entries live under ~/.rtm/plugin-knowledge/. Each plugin
 * gets a single JSON file keyed by a sanitised version of its name
 * (the plugin_id contains characters like '|' which aren't filename-
 * safe across all filesystems).
 */
export function getKnowledgeDir (): string {
  const dir = path.join(os.homedir(), '.rtm', 'plugin-knowledge')
  if (!fs.existsSync(dir)) {
    try { fs.mkdirSync(dir, { recursive: true }) } catch { /* permission denied — callers handle missing dir */ }
  }
  return dir
}

function nameToFilename (name: string): string {
  // Replace anything that isn't [A-Za-z0-9._-] with '_', collapse repeats,
  // trim leading/trailing dots and underscores.
  return name
    .replace(/[^A-Za-z0-9._-]+/g, '_')
    .replace(/^[._]+|[._]+$/g, '')
    .slice(0, 80)  // filesystem cap
}

export function knowledgePathFor (pluginName: string): string {
  return path.join(getKnowledgeDir(), `${nameToFilename(pluginName)}.json`)
}

export function saveReference (entry: ReferenceProfile): void {
  const p = knowledgePathFor(entry.name)
  const tmp = p + '.tmp'
  try {
    fs.writeFileSync(tmp, JSON.stringify(entry, null, 2), 'utf8')
    fs.renameSync(tmp, p)
  } catch (e) {
    try { fs.unlinkSync(tmp) } catch { /* best-effort cleanup */ }
    throw e
  }
}

export function loadReference (pluginName: string): ReferenceProfile | null {
  const p = knowledgePathFor(pluginName)
  if (!fs.existsSync(p)) return null
  try {
    return JSON.parse(fs.readFileSync(p, 'utf8')) as ReferenceProfile
  } catch {
    return null
  }
}

// 5.7.1 v5 HIGH fix: memoize the full plugin-knowledge corpus by
// directory mtime. Pre-fix the renderer's
// `rtmsend-best-plugins-for-bands` IPC fired on every band edit, and
// each call did readdirSync + readFileSync × ~30 JSON files
// synchronously on the main thread. Combined with the 4 s polling
// load this was a major contributor to the spindump's uv_fs_open
// 30 % saturation. Now we only re-read when the directory's mtime
// advances (a new auto-capture / user-recapture writes a file, which
// updates the dir mtime).
let referencesCache: { dirMtime: number; entries: ReferenceProfile[] } | null = null

export function listAllReferences (): ReferenceProfile[] {
  const dir = getKnowledgeDir()
  let dirMtime = 0
  try { dirMtime = fs.statSync(dir).mtimeMs } catch { /* dir missing — treat as empty */ }
  if (referencesCache && referencesCache.dirMtime === dirMtime) {
    return referencesCache.entries
  }
  let files: string[] = []
  try {
    files = fs.readdirSync(dir).filter(f => f.endsWith('.json'))
  } catch { /* dir doesn't exist yet — return empty list */ }
  const out: ReferenceProfile[] = []
  for (const f of files) {
    try {
      const entry = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')) as ReferenceProfile
      out.push(entry)
    } catch { /* skip malformed */ }
  }
  referencesCache = { dirMtime, entries: out }
  return out
}

