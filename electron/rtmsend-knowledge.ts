export function inferArchetype (pluginName: string): { tags: ArchetypeTag[]; notes?: string } {
  const needle = pluginName.toLowerCase()
  for (const a of KNOWN_ARCHETYPES) {
    if (needle.includes(a.name_contains.toLowerCase())) {
      return { tags: a.tags, notes: a.notes }
    }
  }
  // Heuristics for plugins we don't know about by name. Caller will
  // refine these from the auto-detect output (e.g. if we found
  // numbered bands, the plugin is 'parametric').
  if (needle.includes('graphic')) return { tags: ['graphic', 'minimum-phase'] }
  if (needle.includes('pultec')) return { tags: ['pultec', 'vintage'] }
  if (needle.includes('1073') || needle.includes('neve')) return { tags: ['console-strip', 'vintage'] }
  if (needle.includes('ssl') && needle.includes('eq')) return { tags: ['console-strip'] }
  if (needle.includes('550') && needle.toLowerCase().includes('api')) return { tags: ['console-strip', 'vintage'] }
  if (needle.includes('curve') && needle.includes('eq')) return { tags: ['spline', 'mastering-grade'] }
  if (needle.includes('niveau') || needle.includes('tilt')) return { tags: ['tilt'] }
  if (needle.includes('maag')) return { tags: ['parametric', 'air-band', 'vintage'] }
  if (needle.includes('dyneq') || needle.includes('dynamic eq')) return { tags: ['parametric', 'dynamic'] }
  return { tags: [] }
}
