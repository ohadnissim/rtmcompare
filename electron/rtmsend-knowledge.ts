/**
 * Plugin Knowledge Base — long-term store of what EQ plugins the user
 * has, what kind they are, and what RTMcompare can do with each one.
 *
 * Two storage tiers:
 *
 *   1. ACTIVE profiles (in `rtmsend-profiles.ts` registry, hand-coded)
 *      Plugins where Send-to-plugin works today. Profile object
 *      describes how to translate RTMcompare's 9-band recs into the
 *      plugin's parameter writes.
 *
 *   2. REFERENCE profiles (this module, `~/.rtm/plugin-knowledge/`)
 *      Captured automatically when a plugin is loaded in RTMsend.
 *      Includes the FULL parameter dump, probed scalings, archetype
 *      tags, and free-form notes. Used for:
 *
 *        a. Tool-aware recommendations — RTMcompare knows what tools
 *           the engineer has and tailors band suggestions to match
 *           ("you have a Pultec — try a 60 Hz CPS boost + 100 Hz
 *           atten" instead of generic "+1 dB at 80 Hz").
 *
 *        b. Archetype matching — given a desired sonic character
 *           (warm LF, surgical mid-cut, airy HF), pick the plugin
 *           whose archetype best fits.
 *
 *        c. "Best plugin for THIS move" — given a specific band move
 *           and the set of plugins the user has, rank by suitability.
 *
 *        d. Documentation — auto-generate a markdown reference of
 *           every plugin we've learned about.
 *
 * Plugins that don't fit RTM's 9-band Send model (Pultec / API 550 /
 * Neve 1073 / Bettermaker EQ232D) STILL get a reference profile —
 * just no active profile. Future RTMcompare versions can use these
 * for archetype-aware analysis even though Send doesn't work.
 */

